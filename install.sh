#!/usr/bin/env bash
# openrouter-passthrough bootstrap:
#   1. creates .env with a random SECRET_PREFIX (unless it already exists)
#   2. starts the container
# Override the prefix:  SECRET_PREFIX=your-long-prefix ./install.sh
set -euo pipefail
cd "$(dirname "$0")"

need() { command -v "$1" >/dev/null 2>&1; }

# --- checks -------------------------------------------------------------
need docker || { echo "ERROR: docker not found. Install Docker first: https://docs.docker.com/engine/install/"; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "ERROR: 'docker compose' plugin not available."; exit 1; }

# --- .env ---------------------------------------------------------------
if [ -f .env ]; then
  echo "==> .env found, keeping current settings"
else
  if [ -n "${SECRET_PREFIX:-}" ]; then
    PREFIX="$SECRET_PREFIX"
    echo "==> Using SECRET_PREFIX provided via environment"
  else
    if need openssl; then
      PREFIX="$(openssl rand -hex 16)" # 32 hex chars
    elif [ -r /dev/urandom ]; then
      PREFIX="$(head -c 16 /dev/urandom | od -An -tx1 | tr -d ' \n')"
    else
      echo "ERROR: cannot generate a random prefix. Install openssl or run: SECRET_PREFIX=<32+ chars> $0" >&2
      exit 1
    fi
  fi
  if [ "${#PREFIX}" -lt 16 ]; then
    echo "WARNING: SECRET_PREFIX is shorter than 16 chars — it is the only gate in front of your proxy. Consider a longer one."
  fi
  cat > .env <<EOF
# Generated by install.sh. This prefix is part of your URLs and the only gate
# in front of the proxy — keep it long, random and private.
SECRET_PREFIX=${PREFIX}

# Optional: forward to a different API (defaults are OpenRouter).
#UPSTREAM_URL=https://openrouter.ai
#UPSTREAM_HOST=openrouter.ai
EOF
  chmod 600 .env
  echo "==> .env created (SECRET_PREFIX: ${#PREFIX} chars)"
fi

# --- up -----------------------------------------------------------------
docker compose up -d

PREFIX_NOW="$(grep -E '^SECRET_PREFIX=' .env | head -n1 | cut -d= -f2-)"
echo
echo "==> Container is up."
echo "    Your SECRET_PREFIX: ${PREFIX_NOW}"
echo "    Base URL for apps:  https://your.domain/${PREFIX_NOW}"
echo "    Find it again later:  grep SECRET_PREFIX .env"
echo
echo "    Local test:  curl -s -o /dev/null -w '%{http_code}\n' http://127.0.0.1:8080/${PREFIX_NOW}/api/v1/models"
echo "    (any HTTP code from the upstream edge means the chain works;"
echo "     from a blocked region expect 403 here — that is still success for the proxy itself)"
echo
echo "==> Next: expose it through your reverse proxy — see README.md"
echo "    Pangolin: examples/pangolin · Caddy: examples/caddy · NPM: examples/nginx-proxy-manager · Traefik: examples/traefik"
